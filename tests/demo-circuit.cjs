const assert = require("assert");
const Provider = require("../demo_2027_provider.js");
const p = new Provider();
p.generateFixture("asoc-demo", "maxi-a", { start: "2027-04-04", blocked: ["2027-04-11"], gameDay: 0 });
const m = p.getDelegateMatches("delegado-a", "maxi-a")[0];
p.loadDelegateResult("delegado-a", "maxi-a", m.partido_numero, 70, 60);
assert.strictEqual(p.getTable("maxi-a").some((r) => r.pts === 2), true);
assert.throws(() => p.loadDelegateResult("delegado-b", "maxi-a", m.partido_numero, 70, 60), /no puede modificar/);
p.setCategoryClosed("maxi-a", true);
assert.throws(() => p.loadDelegateResult("delegado-a", "maxi-a", m.partido_numero, 70, 60), /cerrada/);
p.annulResult("maxi-a", m.partido_numero);
assert.strictEqual(p.getMatches("maxi-a").find((x) => x.partido_numero === m.partido_numero).estado_resultado, "pendiente");
console.log("DEMO_CIRCUIT_OK");
